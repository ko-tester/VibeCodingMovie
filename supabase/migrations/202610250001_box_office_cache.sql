-- Schema matches ERD.md exactly. No raw API payload or secret is stored in these tables.

CREATE TABLE IF NOT EXISTS public.movies (
    movie_code TEXT PRIMARY KEY,
    movie_name TEXT NOT NULL,
    release_date DATE NULL
);

CREATE TABLE IF NOT EXISTS public.box_office_periods (
    period_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_type TEXT NOT NULL CHECK (period_type IN ('daily', 'weekly', 'weekend')),
    base_date DATE NOT NULL,
    source TEXT NOT NULL,
    collected_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NULL,
    CONSTRAINT box_office_periods_period_date_key UNIQUE (period_type, base_date)
);

CREATE TABLE IF NOT EXISTS public.box_office_results (
    period_id BIGINT NOT NULL REFERENCES public.box_office_periods(period_id),
    movie_code TEXT NOT NULL REFERENCES public.movies(movie_code),
    rank SMALLINT NOT NULL CHECK (rank > 0),
    revenue BIGINT NOT NULL CHECK (revenue >= 0),
    total_revenue BIGINT NOT NULL CHECK (total_revenue >= 0),
    audience BIGINT NOT NULL CHECK (audience >= 0),
    total_audience BIGINT NOT NULL CHECK (total_audience >= 0),
    CONSTRAINT box_office_results_pkey PRIMARY KEY (period_id, movie_code),
    CONSTRAINT box_office_results_period_rank_key UNIQUE (period_id, rank)
);

ALTER TABLE public.movies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.box_office_periods ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.box_office_results ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.movies FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.box_office_periods FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.box_office_results FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.save_box_office_period(
    p_period_type TEXT,
    p_base_date DATE,
    p_source TEXT,
    p_collected_at TIMESTAMPTZ,
    p_expires_at TIMESTAMPTZ,
    p_movies JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_period_id BIGINT;
    v_existing_collected_at TIMESTAMPTZ;
    v_row_count INTEGER;
    v_distinct_movies INTEGER;
    v_distinct_ranks INTEGER;
BEGIN
    IF p_period_type IS NULL OR p_period_type NOT IN ('daily', 'weekly', 'weekend') OR p_base_date IS NULL THEN
        RAISE EXCEPTION 'invalid period key' USING ERRCODE = '22023';
    END IF;
    IF p_source IS NULL OR p_source = '' OR p_collected_at IS NULL OR p_expires_at IS NULL OR p_expires_at <= p_collected_at THEN
        RAISE EXCEPTION 'invalid snapshot metadata' USING ERRCODE = '22023';
    END IF;
    IF p_movies IS NULL OR jsonb_typeof(p_movies) <> 'array' OR jsonb_array_length(p_movies) > 10 THEN
        RAISE EXCEPTION 'invalid movie array' USING ERRCODE = '22023';
    END IF;

    -- Serialize writers for this period key, including the not-yet-inserted case.
    PERFORM pg_advisory_xact_lock(hashtextextended(p_period_type || ':' || p_base_date::TEXT, 0));

    SELECT period_id, collected_at
      INTO v_period_id, v_existing_collected_at
      FROM public.box_office_periods
     WHERE period_type = p_period_type AND base_date = p_base_date
     FOR UPDATE;

    IF FOUND AND p_collected_at <= v_existing_collected_at THEN
        RETURN jsonb_build_object(
            'saved', FALSE,
            'reason', 'stale_request',
            'currentCollectedAt', v_existing_collected_at
        );
    END IF;

    SELECT count(*)::INTEGER,
           count(DISTINCT x.movie_code)::INTEGER,
           count(DISTINCT x.rank)::INTEGER
      INTO v_row_count, v_distinct_movies, v_distinct_ranks
      FROM jsonb_to_recordset(p_movies) AS x(
          movie_code TEXT,
          movie_name TEXT,
          release_date DATE,
          rank SMALLINT,
          revenue BIGINT,
          total_revenue BIGINT,
          audience BIGINT,
          total_audience BIGINT
      );

    IF EXISTS (
        SELECT 1
          FROM jsonb_to_recordset(p_movies) AS x(
              movie_code TEXT,
              movie_name TEXT,
              release_date DATE,
              rank SMALLINT,
              revenue BIGINT,
              total_revenue BIGINT,
              audience BIGINT,
              total_audience BIGINT
          )
         WHERE movie_code IS NULL OR btrim(movie_code) = ''
            OR movie_name IS NULL OR btrim(movie_name) = ''
            OR rank IS NULL OR rank < 1 OR rank > 10
            OR revenue IS NULL OR revenue < 0
            OR total_revenue IS NULL OR total_revenue < 0
            OR audience IS NULL OR audience < 0
            OR total_audience IS NULL OR total_audience < 0
    ) OR v_row_count <> v_distinct_movies OR v_row_count <> v_distinct_ranks THEN
        RAISE EXCEPTION 'invalid movie rows' USING ERRCODE = '22023';
    END IF;

    -- 1. Upsert the movie dimension, in a stable order to reduce cross-period deadlocks.
    INSERT INTO public.movies (movie_code, movie_name, release_date)
    SELECT x.movie_code, x.movie_name, x.release_date
      FROM jsonb_to_recordset(p_movies) AS x(
          movie_code TEXT,
          movie_name TEXT,
          release_date DATE,
          rank SMALLINT,
          revenue BIGINT,
          total_revenue BIGINT,
          audience BIGINT,
          total_audience BIGINT
      )
     ORDER BY x.movie_code
    ON CONFLICT (movie_code) DO UPDATE
       SET movie_name = EXCLUDED.movie_name,
           release_date = EXCLUDED.release_date;

    -- 2. Create or refresh the period row after rejecting out-of-order requests.
    INSERT INTO public.box_office_periods (period_type, base_date, source, collected_at, expires_at)
    VALUES (p_period_type, p_base_date, p_source, p_collected_at, p_expires_at)
    ON CONFLICT (period_type, base_date) DO UPDATE
       SET source = EXCLUDED.source,
           collected_at = EXCLUDED.collected_at,
           expires_at = EXCLUDED.expires_at
    RETURNING period_id INTO v_period_id;

    -- 3. Replace all rows for this period, including removing movies no longer in Top 10.
    DELETE FROM public.box_office_results WHERE period_id = v_period_id;

    INSERT INTO public.box_office_results (
        period_id, movie_code, rank, revenue, total_revenue, audience, total_audience
    )
    SELECT v_period_id, x.movie_code, x.rank, x.revenue, x.total_revenue, x.audience, x.total_audience
      FROM jsonb_to_recordset(p_movies) AS x(
          movie_code TEXT,
          movie_name TEXT,
          release_date DATE,
          rank SMALLINT,
          revenue BIGINT,
          total_revenue BIGINT,
          audience BIGINT,
          total_audience BIGINT
      )
     ORDER BY x.rank;

    RETURN jsonb_build_object(
        'saved', TRUE,
        'periodId', v_period_id,
        'collectedAt', p_collected_at,
        'expiresAt', p_expires_at
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.read_box_office_period(
    p_period_type TEXT,
    p_base_date DATE
)
RETURNS JSONB
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
    SELECT jsonb_build_object(
        'periodType', p.period_type,
        'baseDate', p.base_date,
        'source', p.source,
        'collectedAt', p.collected_at,
        'expiresAt', p.expires_at,
        'movies', COALESCE(
            jsonb_agg(
                jsonb_build_object(
                    'movieCode', m.movie_code,
                    'title', m.movie_name,
                    'releaseDate', m.release_date,
                    'rank', r.rank,
                    'revenue', r.revenue,
                    'totalRevenue', r.total_revenue,
                    'audience', r.audience,
                    'totalAudience', r.total_audience
                ) ORDER BY r.rank
            ) FILTER (WHERE r.movie_code IS NOT NULL),
            '[]'::jsonb
        )
    )
      FROM public.box_office_periods AS p
      LEFT JOIN public.box_office_results AS r ON r.period_id = p.period_id
      LEFT JOIN public.movies AS m ON m.movie_code = r.movie_code
     WHERE p.period_type = p_period_type AND p.base_date = p_base_date
     GROUP BY p.period_id;
$$;

REVOKE ALL ON FUNCTION public.save_box_office_period(TEXT, DATE, TEXT, TIMESTAMPTZ, TIMESTAMPTZ, JSONB) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.read_box_office_period(TEXT, DATE) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.save_box_office_period(TEXT, DATE, TEXT, TIMESTAMPTZ, TIMESTAMPTZ, JSONB) TO service_role;
GRANT EXECUTE ON FUNCTION public.read_box_office_period(TEXT, DATE) TO service_role;
